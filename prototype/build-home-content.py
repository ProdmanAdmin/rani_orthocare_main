HTML_OUT.write_text(page, encoding="utf-8")
print(f"Wrote {HTML_OUT.relative_to(ROOT)} ({len(sections)} sections)")
if not CHROME.exists():
    raise SystemExit("Chrome not found: the PDF was not made")
subprocess.run([str(CHROME), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                "--virtual-time-budget=15000", f"--print-to-pdf={PDF_OUT}", HTML_OUT.as_uri()],
               check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
# The prototype offers the PDF for download, so keep a copy beside its pages.
shutil.copy2(PDF_OUT, HERE / "home-page-content.pdf")
print(f"Wrote {PDF_OUT.relative_to(ROOT)}")
